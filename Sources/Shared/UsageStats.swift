// UsageStats.swift
//
// Local usage counters for the launcher and the clipboard history, kept in
// ~/Library/Application Support/Launcher/usage.json in daily buckets. Nothing
// is sent anywhere. What is recorded:
// - launcher: opens, closes without opening anything (empty or typed), Enter
//   on a keyword still waiting for its argument, which workflow ran (by its
//   first keyword, never the argument), fallback count, and the first word of
//   multi-word fallback inputs when it is a keyword or a typo away from one of
//   4 letters or more (a mistyped keyword), and which apps were opened (by
//   bundle ID);
// - previews, weather and transit: requests answered and failures, by
//   error, and how often the departure board is shown;
// - calendar: how often the event list is shown (never what it lists);
// - built-ins: how often each one's answer is copied (never the input or
//   the answer);
// - clipboard: copies and restores per source app (bundle ID), copies by
//   kind, skipped copies by reason, pins and unpins. Never any content or
//   file path;
// - pomodoro: focus sessions that ran their full length, on the day they
//   ended.
// Turn it off with Config.usageTracking; the menu bar's "Usage…" shows a
// summary, and `/stats` in the launcher the last few days (Sources/Stats).
// The launcher also ranks its list with the totals (`totals()`): apps you
// open more often, and keywords you run more often, come first.

import Cocoa

/// The simple counters, named as they appear in usage.json.
enum UsageCounter: String, Sendable {
    case launcherOpened = "launcher.opened"
    /// Closed without opening a URL, with nothing typed.
    case launcherClosedEmpty = "launcher.closedEmpty"
    /// Closed without opening a URL, with something typed.
    case launcherClosedTyped = "launcher.closedTyped"
    /// Enter on a keyword that needs an argument, typed alone.
    case launcherEnterNeedsArgument = "launcher.enterNeedsArgument"
    case launcherFallback = "launcher.fallback"
    /// Enter on `/…` that no workflow takes (Config.commandPrefix). Its
    /// first word is kept like a fallback word.
    case launcherUnknownCommand = "launcher.unknownCommand"
    /// An installed app was opened; which one is in UsageDay.appsOpened.
    case launcherOpenedApp = "launcher.openedApp"
    /// A command card under the empty input was clicked (which one is
    /// counted if it is then run, under keywords).
    case launcherCardPicked = "launcher.cardPicked"
    /// The weather above the input was clicked (it types `/weather`).
    case launcherWeatherStripClicked = "launcher.weatherStripClicked"
    /// The next meeting above the input was clicked (it types `/cal`).
    case launcherMeetingStripClicked = "launcher.meetingStripClicked"

    case previewLoaded = "preview.loaded"
    case previewFailed = "preview.failed"

    case weatherLoaded = "weather.loaded"
    // Failures are counted as "weather.failed.<WeatherError.usageName>".

    case transitLoaded = "transit.loaded"
    // Failures are counted as "transit.failed.<TransitError.usageName>".
    /// The departure board was shown (once per launcher opening).
    case transitShown = "transit.shown"

    /// The event list was shown (once per launcher opening).
    case calendarShown = "calendar.shown"

    /// Enter copied a built-in's answer (Sources/BuiltIns), by built-in;
    /// never the input or the answer.
    case builtInCalculation = "builtin.calculation"
    case builtInConversion = "builtin.conversion"
    case builtInTime = "builtin.time"
    case builtInUUID = "builtin.uuid"
    case builtInTimestamp = "builtin.timestamp"
    case builtInDate = "builtin.date"
    case builtInWeek = "builtin.week"

    case clipboardCopiedText = "clipboard.copied.text"
    case clipboardCopiedImage = "clipboard.copied.image"
    case clipboardCopiedFiles = "clipboard.copied.files"
    /// Marked Concealed / Transient / AutoGenerated by the app.
    case clipboardSkippedMarked = "clipboard.skipped.marked"
    /// Copied in one of Config.clipboardIgnoredApps.
    case clipboardSkippedApp = "clipboard.skipped.app"
    /// Text over Config.clipboardMaxTextBytes, or only whitespace.
    case clipboardSkippedText = "clipboard.skipped.text"
    /// Image too large, or unreadable.
    case clipboardSkippedImage = "clipboard.skipped.image"
    case clipboardRestoreFailed = "clipboard.restoreFailed"
    case clipboardPinned = "clipboard.pinned"
    case clipboardUnpinned = "clipboard.unpinned"

    /// A focus session ran its full length (skipped ones don't count),
    /// counted on the day it ended (record(_:on:)).
    case pomodoroFocusCompleted = "pomodoro.focusCompleted"
}

/// One day of counters. Every field is a plain name → count map, so a field
/// added later reads as empty in older files.
struct UsageDay: Codable {
    var counts: [String: Int] = [:]
    /// "pr" for a workflow run without an argument, "pr …" with one.
    var keywords: [String: Int] = [:]
    var fallbackWords: [String: Int] = [:]
    /// Keyed by bundle ID ("unknown" when the app had none).
    var clipboardCopies: [String: Int] = [:]
    var clipboardRestores: [String: Int] = [:]
    /// Apps opened from the launcher, keyed by bundle ID ("unknown" when
    /// the app had none).
    var appsOpened: [String: Int] = [:]

    init() {}

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        counts = try container.decodeIfPresent([String: Int].self, forKey: .counts) ?? [:]
        keywords = try container.decodeIfPresent([String: Int].self, forKey: .keywords) ?? [:]
        fallbackWords = try container.decodeIfPresent([String: Int].self, forKey: .fallbackWords) ?? [:]
        clipboardCopies = try container.decodeIfPresent([String: Int].self, forKey: .clipboardCopies) ?? [:]
        clipboardRestores = try container.decodeIfPresent([String: Int].self, forKey: .clipboardRestores) ?? [:]
        appsOpened = try container.decodeIfPresent([String: Int].self, forKey: .appsOpened) ?? [:]
    }

    /// Adds every count of `other` to this one.
    mutating func add(_ other: UsageDay) {
        counts.merge(other.counts, uniquingKeysWith: +)
        keywords.merge(other.keywords, uniquingKeysWith: +)
        fallbackWords.merge(other.fallbackWords, uniquingKeysWith: +)
        clipboardCopies.merge(other.clipboardCopies, uniquingKeysWith: +)
        clipboardRestores.merge(other.clipboardRestores, uniquingKeysWith: +)
        appsOpened.merge(other.appsOpened, uniquingKeysWith: +)
    }
}

/// Counts over every kept day, for ranking the launcher's list.
struct UsageTotals: Sendable {
    /// Bundle ID → times opened.
    var apps: [String: Int] = [:]
    /// Same keys as UsageDay.keywords: "pr", or "pr …" with an argument.
    var keywords: [String: Int] = [:]
}

/// File format: { "version": 1, "days": { "2026-11-01": {...}, ... } }.
/// StoreFile reads only version 1.
private struct StoredUsage: Codable {
    static let currentVersion = 1
    var version = Self.currentVersion
    var days: [String: UsageDay] = [:]
}

@MainActor
final class UsageStats {
    static let shared = UsageStats()

    /// usage.json: read at launch, saved 5 s after a change and on quit.
    private let file: StoreFile
    var fileURL: URL { file.url }
    /// The current time and calendar. Only the self-test passes others.
    private let now: @MainActor () -> Date
    private let calendar: Calendar
    private var stored = StoredUsage()
    /// Key of the newest bucket, so old days are pruned once a day.
    private var lastDayKey: String?

    /// Fallback words longer than this, or with other characters than
    /// letters, digits, "-" and "_", are not keyword candidates (a pasted URL,
    /// a path, an email address...) and are not kept.
    private static let maxFallbackWordLength = 20
    /// Words past this many distinct ones in a day are counted as "(other)".
    private static let maxFallbackWordsPerDay = 50

    private convenience init() {
        self.init(fileURL: ClipboardStore.directory.appendingPathComponent("usage.json"),
                  now: { Date() }, calendar: .autoupdatingCurrent)
    }

    /// Private, so `shared` is the only instance on usage.json: two would
    /// overwrite each other's counts. The self-test uses makeForSelfTest.
    private init(fileURL: URL, now: @escaping @MainActor () -> Date, calendar: Calendar) {
        file = StoreFile(url: fileURL, name: "usage stats", kind: .usage)
        self.now = now
        self.calendar = calendar
        guard Config.usageTracking else { return }
        stored = file.load(StoredUsage.self, currentVersion: StoredUsage.currentVersion) ?? StoredUsage()
        prune()
    }

    // MARK: Recording

    func record(_ counter: UsageCounter) {
        record(named: counter.rawValue)
    }

    /// Counts `counter` on the local day of `date` rather than today, for
    /// something noticed later than it happened (a pomodoro session that
    /// ended while the Mac slept or the app was closed). Dropped when that
    /// day is older than the days kept.
    func record(_ counter: UsageCounter, on date: Date) {
        update(on: date) { $0.counts[counter.rawValue, default: 0] += 1 }
    }

    func recordWeatherFailure(_ error: WeatherError) {
        record(named: "weather.failed.\(error.usageName)")
    }

    func recordTransitFailure(_ error: TransitError) {
        record(named: "transit.failed.\(error.usageName)")
    }

    /// The key a workflow run is counted under in `keywords`: its first
    /// keyword, "pr", or "pr …" for the argument form. Read back by the
    /// launcher's ranking, the command cards and `/stats`.
    nonisolated static func keywordKey(_ keyword: String, withArgument: Bool) -> String {
        withArgument ? "\(keyword) …" : keyword
    }

    /// The keyword a `keywords` key counts runs of: "pr" for "pr" and "pr …".
    nonisolated static func keyword(fromKey key: String) -> String {
        key.hasSuffix(" …") ? String(key.dropLast(2)) : key
    }

    /// Enter ran a workflow, or the fallback with `input` as its query.
    /// `keywords` are every workflow keyword, which a fallback word must be
    /// close to for it to be kept.
    func recordLaunch(_ source: CommandSource, input: String, keywords: Set<String>) {
        switch source {
        case .workflow(let keyword, let withArgument):
            update { $0.keywords[Self.keywordKey(keyword, withArgument: withArgument), default: 0] += 1 }
        case .fallback:
            update { day in
                day.counts[UsageCounter.launcherFallback.rawValue, default: 0] += 1
                Self.addFallbackWord(in: input, keywords: keywords, to: &day)
            }
        }
    }

    /// Enter on command input no workflow takes, `body` being what follows
    /// the prefix (`jria abc-42` for `/jria abc-42`): counted, and its first
    /// word kept under the same rule as a fallback's, so mistyped keywords
    /// still show up.
    func recordUnknownCommand(_ body: String, keywords: Set<String>) {
        update { day in
            day.counts[UsageCounter.launcherUnknownCommand.rawValue, default: 0] += 1
            Self.addFallbackWord(in: body, keywords: keywords, to: &day)
        }
    }

    private static func addFallbackWord(in input: String, keywords: Set<String>, to day: inout UsageDay) {
        guard Config.usageTrackFallbackWords, let word = fallbackWord(in: input, keywords: keywords) else { return }
        let key = day.fallbackWords[word] != nil || day.fallbackWords.count < maxFallbackWordsPerDay
            ? word : "(other)"
        day.fallbackWords[key, default: 0] += 1
    }

    func recordClipboardCopy(_ content: ClipContent, bundleID: String?) {
        let counter: UsageCounter
        switch content {
        case .text: counter = .clipboardCopiedText
        case .image: counter = .clipboardCopiedImage
        case .files: counter = .clipboardCopiedFiles
        }
        update { day in
            day.counts[counter.rawValue, default: 0] += 1
            day.clipboardCopies[bundleID ?? "unknown", default: 0] += 1
        }
    }

    /// The launcher opened the app with this bundle ID.
    func recordAppOpened(bundleID: String?) {
        update { day in
            day.counts[UsageCounter.launcherOpenedApp.rawValue, default: 0] += 1
            day.appsOpened[bundleID ?? "unknown", default: 0] += 1
        }
    }

    /// An item copied from `bundleID` was put back on the clipboard.
    func recordClipboardRestore(bundleID: String?) {
        update { $0.clipboardRestores[bundleID ?? "unknown", default: 0] += 1 }
    }

    private func record(named name: String) {
        update { $0.counts[name, default: 0] += 1 }
    }

    /// Applies `change` to today's bucket, or to `date`'s day when given.
    private func update(on date: Date? = nil, _ change: (inout UsageDay) -> Void) {
        guard Config.usageTracking else { return }
        let today = dayKey(for: now())
        if today != lastDayKey { prune() }
        lastDayKey = today
        var key = today
        if let date {
            // Later than today counts as today; before the days kept, nowhere.
            key = min(dayKey(for: date), today)
            guard key >= firstDayKey(keeping: Config.usageRetentionDays) else { return }
        }
        change(&stored.days[key, default: UsageDay()])
        scheduleSave()
    }

    /// The first word of a fallback input with at least two words,
    /// lowercased, if it is one of `keywords` or a typo away from one: one
    /// letter added, missing, changed or swapped with the next for keywords
    /// of 4 letters, two for 5 letters or more. A keyword of 1 to 3 letters
    /// must match exactly, since a typo away from "pr" is any word like "pa"
    /// or "or". Any other word is what was searched for, and is not kept.
    private static func fallbackWord(in input: String, keywords: Set<String>) -> String? {
        let parts = input.trimmingCharacters(in: .whitespacesAndNewlines)
            .split(maxSplits: 1, whereSeparator: \.isWhitespace)
        guard parts.count == 2 else { return nil }
        let word = parts[0].lowercased()
        guard word.count <= maxFallbackWordLength,
              word.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" })
        else { return nil }
        let isNearKeyword = keywords.contains { keyword in
            typoDistance(word, keyword) <= Self.allowedTypos(for: keyword)
        }
        return isNearKeyword ? word : nil
    }

    private static func allowedTypos(for keyword: String) -> Int {
        keyword.count >= 5 ? 2 : keyword.count == 4 ? 1 : 0
    }

    /// Edits (insert, delete, replace, swap two neighbors) from `a` to `b`:
    /// the optimal string alignment distance. Both are short words.
    private static func typoDistance(_ a: String, _ b: String) -> Int {
        let a = Array(a)
        let b = Array(b)
        if a.isEmpty || b.isEmpty { return max(a.count, b.count) }
        var table = [[Int]](repeating: [Int](repeating: 0, count: b.count + 1), count: a.count + 1)
        for i in 0...a.count { table[i][0] = i }
        for j in 0...b.count { table[0][j] = j }
        for i in 1...a.count {
            for j in 1...b.count {
                let cost = a[i - 1] == b[j - 1] ? 0 : 1
                var best = min(table[i - 1][j] + 1, table[i][j - 1] + 1, table[i - 1][j - 1] + cost)
                if i > 1, j > 1, a[i - 1] == b[j - 2], a[i - 2] == b[j - 1] {
                    best = min(best, table[i - 2][j - 2] + 1)
                }
                table[i][j] = best
            }
        }
        return table[a.count][b.count]
    }

    #if SELFTEST
    static func fallbackWordForSelfTest(in input: String, keywords: Set<String>) -> String? {
        fallbackWord(in: input, keywords: keywords)
    }
    #endif

    // MARK: Totals

    /// Apps opened and keywords run over every kept day (up to
    /// Config.usageRetentionDays). Empty when Config.usageTracking is off.
    func totals() -> UsageTotals {
        var totals = UsageTotals()
        guard Config.usageTracking else { return totals }
        for day in stored.days.values {
            totals.apps.merge(day.appsOpened, uniquingKeysWith: +)
            totals.keywords.merge(day.keywords, uniquingKeysWith: +)
        }
        totals.apps["unknown"] = nil
        return totals
    }

    // MARK: Reading

    /// Every counter of the last `days` days, today included, added up.
    func merged(days: Int) -> UsageDay {
        let cutoff = firstDayKey(keeping: days)
        var total = UsageDay()
        for (key, day) in stored.days where key >= cutoff {
            total.add(day)
        }
        return total
    }

    /// The day counting started, when that is later than the first of the
    /// last `days` days: what "never run in that time" is worth. Today when
    /// nothing was recorded yet; nil when the counters reach back over all
    /// of them.
    func countingSince(withinLast days: Int) -> Date? {
        let today = calendar.startOfDay(for: now())
        guard let oldest = stored.days.keys.min() else { return today }
        guard oldest > firstDayKey(keeping: days) else { return nil }
        let parts = oldest.split(separator: "-").compactMap { Int($0) }
        guard parts.count == 3,
              let date = calendar.date(from: DateComponents(year: parts[0], month: parts[1], day: parts[2]))
        else { return today }
        return date
    }

    // MARK: Summary

    /// The days the "Usage…" alert sums up.
    nonisolated static let summaryDays = 30

    /// A plain-text summary of the last `days` days, for the "Usage…" alert.
    func summary(days: Int) -> String {
        let total = merged(days: days)
        func count(_ counter: UsageCounter) -> Int { total.counts[counter.rawValue] ?? 0 }
        func top(_ map: [String: Int], _ limit: Int) -> String {
            let sorted = map.sorted { $0.value != $1.value ? $0.value > $1.value : $0.key < $1.key }
            let lines = sorted.prefix(limit).map { "  \($0.key): \($0.value)" }
            return lines.isEmpty ? "  (none)" : lines.joined(separator: "\n")
        }

        let builtIns: Int = count(.builtInCalculation) + count(.builtInConversion) + count(.builtInTime)
            + count(.builtInUUID) + count(.builtInTimestamp) + count(.builtInDate) + count(.builtInWeek)
        let launched: Int = total.keywords.values.reduce(0, +) + count(.launcherFallback) + count(.launcherOpenedApp)
            + builtIns
        let closed = count(.launcherClosedEmpty) + count(.launcherClosedTyped)
        let failurePrefix = "weather.failed."
        var weatherFailures: [String: Int] = [:]
        for (name, value) in total.counts where name.hasPrefix(failurePrefix) {
            weatherFailures[String(name.dropFirst(failurePrefix.count))] = value
        }
        var appsOpened: [String: Int] = [:]
        for (id, value) in total.appsOpened {
            appsOpened[Self.appName(for: id), default: 0] += value
        }
        let skipped = count(.clipboardSkippedMarked) + count(.clipboardSkippedApp)
            + count(.clipboardSkippedText) + count(.clipboardSkippedImage)
        // Spelled out step by step: as one chain it is too slow to type-check.
        let appIDs: Set<String> = Set(total.clipboardCopies.keys).union(total.clipboardRestores.keys)
        let byCopies: [String] = appIDs.sorted { lhs, rhs in
            let left: Int = total.clipboardCopies[lhs] ?? 0
            let right: Int = total.clipboardCopies[rhs] ?? 0
            return left != right ? left > right : lhs < rhs
        }
        var apps: [String] = []
        for id in byCopies.prefix(10) {
            let copies: Int = total.clipboardCopies[id] ?? 0
            let restores: Int = total.clipboardRestores[id] ?? 0
            apps.append("  \(Self.appName(for: id)): \(copies) copied, \(restores) restored")
        }

        let builtInKinds: String = "\(count(.builtInCalculation)) calculations, "
            + "\(count(.builtInConversion)) conversions, \(count(.builtInTime)) times, "
            + "\(count(.builtInUUID)) UUIDs, \(count(.builtInTimestamp)) timestamps, "
            + "\(count(.builtInDate)) dates, \(count(.builtInWeek)) weeks"
        let builtInLine = "Built-ins copied: \(builtIns) (\(builtInKinds))"

        var lines: [String] = [
            "Launcher: opened \(count(.launcherOpened)), ran \(launched)",
            "  closed without running: \(closed) (\(count(.launcherClosedTyped)) with text typed)",
            "  Enter on a keyword missing its argument: \(count(.launcherEnterNeedsArgument))",
            "  Enter on an unknown command: \(count(.launcherUnknownCommand))",
            "  command cards clicked: \(count(.launcherCardPicked))",
            "  weather strip clicked: \(count(.launcherWeatherStripClicked))",
            "  next meeting clicked: \(count(.launcherMeetingStripClicked))",
            "Keywords:",
            top(total.keywords, 10),
            "Apps opened: \(count(.launcherOpenedApp))",
            top(appsOpened, 10),
            "Fallback: \(count(.launcherFallback)), first words:",
            top(total.fallbackWords, 10),
            builtInLine,
            "Previews: \(count(.previewLoaded)) loaded, \(count(.previewFailed)) failed",
            "Weather: \(count(.weatherLoaded)) loaded, \(weatherFailures.values.reduce(0, +)) failed",
        ]
        if !weatherFailures.isEmpty { lines.append(top(weatherFailures, 10)) }
        lines.append("Calendar: shown \(count(.calendarShown))")
        lines.append("Pomodoro: \(count(.pomodoroFocusCompleted)) focus sessions finished")
        let copied = "\(count(.clipboardCopiedText)) text, \(count(.clipboardCopiedImage)) images, "
            + "\(count(.clipboardCopiedFiles)) files"
        lines += [
            "Clipboard: \(copied) copied",
            "  skipped: \(skipped), restores failed: \(count(.clipboardRestoreFailed))",
            "  pinned: \(count(.clipboardPinned)), unpinned: \(count(.clipboardUnpinned))",
            apps.isEmpty ? "  (none)" : apps.joined(separator: "\n"),
        ]
        return lines.joined(separator: "\n")
    }

    /// The app's name as Finder shows it, else the bundle ID itself.
    static func appName(for bundleID: String) -> String {
        guard bundleID != "unknown",
              let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
        else { return bundleID }
        return FileManager.default.displayName(atPath: url.path)
            .replacingOccurrences(of: ".app", with: "")
    }

    // MARK: Storage

    /// The local calendar day, e.g. "2026-11-01".
    private func dayKey(for date: Date) -> String {
        DayKey.of(date, in: calendar)
    }

    /// The oldest day of the last `days` calendar days, today included.
    private func firstDayKey(keeping days: Int) -> String {
        DayKey.first(keeping: days, upTo: now(), in: calendar)
    }

    #if SELFTEST
    static func makeForSelfTest(fileURL: URL, now: @escaping @MainActor () -> Date, calendar: Calendar) -> UsageStats {
        UsageStats(fileURL: fileURL, now: now, calendar: calendar)
    }

    /// The days that have counters, oldest first.
    var dayKeys: [String] { stored.days.keys.sorted() }
    func firstDayKeyForSelfTest(keeping days: Int) -> String { firstDayKey(keeping: days) }
    #endif

    /// Keeps the last Config.usageRetentionDays days, today included.
    private func prune() {
        let cutoff = firstDayKey(keeping: Config.usageRetentionDays)
        let before = stored.days.count
        stored.days = stored.days.filter { $0.key >= cutoff }
        if stored.days.count != before { scheduleSave() }
    }

    private func scheduleSave() {
        file.scheduleSave { self.stored }
    }

    /// Writes any pending change; called on quit.
    func saveNow() {
        file.saveNow()
    }
}
