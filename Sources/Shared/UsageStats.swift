// UsageStats.swift
//
// Local usage counters for the launcher and the clipboard history, kept in
// ~/Library/Application Support/Launcher/usage.json in daily buckets. Nothing
// is sent anywhere. What is recorded:
// - launcher: opens, closes without opening anything (empty or typed), Enter
//   on a keyword still waiting for its argument, which workflow ran (by its
//   first keyword, never the argument), fallback count, and the first word of
//   multi-word fallback inputs (a missing or mistyped keyword);
// - previews and weather: requests answered and failures, by error;
// - clipboard: copies and restores per source app (bundle ID), copies by
//   kind, skipped copies by reason. Never any content or file path.
// Turn it off with Config.usageTracking; the menu bar's "Usage…" shows a
// summary.

import Cocoa

/// The simple counters, named as they appear in usage.json.
enum UsageCounter: String, Sendable {
    case launcherOpened = "launcher.opened"
    /// Closed without opening a URL, with nothing typed.
    case launcherClosedEmpty = "launcher.closedEmpty"
    /// Closed without opening a URL, with something typed.
    case launcherClosedTyped = "launcher.closedTyped"
    /// Enter on a keyword that needs an argument, typed alone.
    case launcherEnterNeedsArgument = "launcher.enterNeedsArgument"
    case launcherFallback = "launcher.fallback"
    /// Enter opened an installed app (which one is not kept).
    case launcherOpenedApp = "launcher.openedApp"

    case previewLoaded = "preview.loaded"
    case previewFailed = "preview.failed"

    case weatherLoaded = "weather.loaded"
    // Failures are counted as "weather.failed.<WeatherError.usageName>".

    case clipboardCopiedText = "clipboard.copied.text"
    case clipboardCopiedImage = "clipboard.copied.image"
    case clipboardCopiedFiles = "clipboard.copied.files"
    /// Marked Concealed / Transient / AutoGenerated by the app.
    case clipboardSkippedMarked = "clipboard.skipped.marked"
    /// Text over Config.clipboardMaxTextBytes, or only whitespace.
    case clipboardSkippedText = "clipboard.skipped.text"
    /// Image too large, or unreadable.
    case clipboardSkippedImage = "clipboard.skipped.image"
    case clipboardRestoreFailed = "clipboard.restoreFailed"
}

/// One day of counters. Every field is a plain name → count map, so a field
/// added later reads as empty in older files.
struct UsageDay: Codable {
    var counts: [String: Int] = [:]
    /// "pr" for a workflow run without an argument, "pr …" with one.
    var keywords: [String: Int] = [:]
    var fallbackWords: [String: Int] = [:]
    /// Keyed by bundle ID ("unknown" when the app had none).
    var clipboardCopies: [String: Int] = [:]
    var clipboardRestores: [String: Int] = [:]

    init() {}

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        counts = try container.decodeIfPresent([String: Int].self, forKey: .counts) ?? [:]
        keywords = try container.decodeIfPresent([String: Int].self, forKey: .keywords) ?? [:]
        fallbackWords = try container.decodeIfPresent([String: Int].self, forKey: .fallbackWords) ?? [:]
        clipboardCopies = try container.decodeIfPresent([String: Int].self, forKey: .clipboardCopies) ?? [:]
        clipboardRestores = try container.decodeIfPresent([String: Int].self, forKey: .clipboardRestores) ?? [:]
    }
}

/// File format: { "version": 1, "days": { "2026-11-01": {...}, ... } }.
private struct StoredUsage: Codable {
    static let currentVersion = 1
    var version = Self.currentVersion
    var days: [String: UsageDay] = [:]
}

@MainActor
final class UsageStats: NSObject {
    static let shared = UsageStats()

    let fileURL: URL
    private var stored = StoredUsage()
    private var saveTimer: Timer?
    /// Key of the newest bucket, so old days are pruned once a day.
    private var lastDayKey: String?

    /// Fallback words longer than this, or with other characters than
    /// letters, digits, "-" and "_", are not keyword candidates (a pasted URL,
    /// a path, an email address...) and are not kept.
    private static let maxFallbackWordLength = 20
    /// Words past this many distinct ones in a day are counted as "(other)".
    private static let maxFallbackWordsPerDay = 50

    private override init() {
        fileURL = ClipboardStore.directory.appendingPathComponent("usage.json")
        super.init()
        guard Config.usageTracking else { return }
        load()
        prune()
    }

    // MARK: Recording

    func record(_ counter: UsageCounter) {
        record(named: counter.rawValue)
    }

    func recordWeatherFailure(_ error: WeatherError) {
        record(named: "weather.failed.\(error.usageName)")
    }

    /// Enter ran a workflow, or the fallback with `input` as its query.
    func recordLaunch(_ source: CommandSource, input: String) {
        switch source {
        case .workflow(let keyword, let withArgument):
            update { $0.keywords[withArgument ? "\(keyword) …" : keyword, default: 0] += 1 }
        case .fallback:
            update { day in
                day.counts[UsageCounter.launcherFallback.rawValue, default: 0] += 1
                guard Config.usageTrackFallbackWords, let word = Self.fallbackWord(in: input) else { return }
                let key = day.fallbackWords[word] != nil || day.fallbackWords.count < Self.maxFallbackWordsPerDay
                    ? word : "(other)"
                day.fallbackWords[key, default: 0] += 1
            }
        }
    }

    func recordClipboardCopy(_ content: ClipContent, bundleID: String?) {
        let counter: UsageCounter
        switch content {
        case .text: counter = .clipboardCopiedText
        case .image: counter = .clipboardCopiedImage
        case .files: counter = .clipboardCopiedFiles
        }
        update { day in
            day.counts[counter.rawValue, default: 0] += 1
            day.clipboardCopies[bundleID ?? "unknown", default: 0] += 1
        }
    }

    /// An item copied from `bundleID` was put back on the clipboard.
    func recordClipboardRestore(bundleID: String?) {
        update { $0.clipboardRestores[bundleID ?? "unknown", default: 0] += 1 }
    }

    private func record(named name: String) {
        update { $0.counts[name, default: 0] += 1 }
    }

    private func update(_ change: (inout UsageDay) -> Void) {
        guard Config.usageTracking else { return }
        let key = Self.dayKey(for: Date())
        if key != lastDayKey { prune() }
        change(&stored.days[key, default: UsageDay()])
        lastDayKey = key
        scheduleSave()
    }

    /// The first word of a fallback input with at least two words,
    /// lowercased, if it could be a keyword.
    private static func fallbackWord(in input: String) -> String? {
        let parts = input.trimmingCharacters(in: .whitespacesAndNewlines)
            .split(maxSplits: 1, whereSeparator: \.isWhitespace)
        guard parts.count == 2 else { return nil }
        let word = parts[0].lowercased()
        guard word.count <= maxFallbackWordLength,
              word.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" })
        else { return nil }
        return word
    }

    // MARK: Summary

    /// A plain-text summary of the last `days` days, for the "Usage…" alert.
    func summary(days: Int = 30) -> String {
        let cutoff = Self.dayKey(for: Date().addingTimeInterval(-Double(days - 1) * 86_400))
        var total = UsageDay()
        for (key, day) in stored.days where key >= cutoff {
            total.counts.merge(day.counts, uniquingKeysWith: +)
            total.keywords.merge(day.keywords, uniquingKeysWith: +)
            total.fallbackWords.merge(day.fallbackWords, uniquingKeysWith: +)
            total.clipboardCopies.merge(day.clipboardCopies, uniquingKeysWith: +)
            total.clipboardRestores.merge(day.clipboardRestores, uniquingKeysWith: +)
        }
        func count(_ counter: UsageCounter) -> Int { total.counts[counter.rawValue] ?? 0 }
        func top(_ map: [String: Int], _ limit: Int) -> String {
            let sorted = map.sorted { $0.value != $1.value ? $0.value > $1.value : $0.key < $1.key }
            let lines = sorted.prefix(limit).map { "  \($0.key): \($0.value)" }
            return lines.isEmpty ? "  (none)" : lines.joined(separator: "\n")
        }

        let launched = total.keywords.values.reduce(0, +) + count(.launcherFallback) + count(.launcherOpenedApp)
        let closed = count(.launcherClosedEmpty) + count(.launcherClosedTyped)
        let failurePrefix = "weather.failed."
        var weatherFailures: [String: Int] = [:]
        for (name, value) in total.counts where name.hasPrefix(failurePrefix) {
            weatherFailures[String(name.dropFirst(failurePrefix.count))] = value
        }
        let skipped = count(.clipboardSkippedMarked) + count(.clipboardSkippedText) + count(.clipboardSkippedImage)
        // Spelled out step by step: as one chain it is too slow to type-check.
        let appIDs: Set<String> = Set(total.clipboardCopies.keys).union(total.clipboardRestores.keys)
        let byCopies: [String] = appIDs.sorted { lhs, rhs in
            let left: Int = total.clipboardCopies[lhs] ?? 0
            let right: Int = total.clipboardCopies[rhs] ?? 0
            return left != right ? left > right : lhs < rhs
        }
        var apps: [String] = []
        for id in byCopies.prefix(10) {
            let copies: Int = total.clipboardCopies[id] ?? 0
            let restores: Int = total.clipboardRestores[id] ?? 0
            apps.append("  \(Self.appName(for: id)): \(copies) copied, \(restores) restored")
        }

        var lines: [String] = [
            "Launcher: opened \(count(.launcherOpened)), ran \(launched)",
            "  closed without running: \(closed) (\(count(.launcherClosedTyped)) with text typed)",
            "  Enter on a keyword missing its argument: \(count(.launcherEnterNeedsArgument))",
            "Keywords:",
            top(total.keywords, 10),
            "Apps opened: \(count(.launcherOpenedApp))",
            "Fallback: \(count(.launcherFallback)), first words:",
            top(total.fallbackWords, 10),
            "Previews: \(count(.previewLoaded)) loaded, \(count(.previewFailed)) failed",
            "Weather: \(count(.weatherLoaded)) loaded, \(weatherFailures.values.reduce(0, +)) failed",
        ]
        if !weatherFailures.isEmpty { lines.append(top(weatherFailures, 10)) }
        let copied = "\(count(.clipboardCopiedText)) text, \(count(.clipboardCopiedImage)) images, "
            + "\(count(.clipboardCopiedFiles)) files"
        lines += [
            "Clipboard: \(copied) copied",
            "  skipped: \(skipped), restores failed: \(count(.clipboardRestoreFailed))",
            apps.isEmpty ? "  (none)" : apps.joined(separator: "\n"),
        ]
        return lines.joined(separator: "\n")
    }

    private static func appName(for bundleID: String) -> String {
        guard bundleID != "unknown",
              let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
        else { return bundleID }
        return FileManager.default.displayName(atPath: url.path)
            .replacingOccurrences(of: ".app", with: "")
    }

    // MARK: Storage

    /// The local calendar day, e.g. "2026-11-01"; sorts like the dates.
    private static func dayKey(for date: Date) -> String {
        let parts = Calendar.current.dateComponents([.year, .month, .day], from: date)
        return String(format: "%04d-%02d-%02d", parts.year ?? 0, parts.month ?? 0, parts.day ?? 0)
    }

    /// Drops days older than Config.usageRetentionDays.
    private func prune() {
        let cutoff = Self.dayKey(for: Date().addingTimeInterval(-Double(Config.usageRetentionDays) * 86_400))
        let before = stored.days.count
        stored.days = stored.days.filter { $0.key >= cutoff }
        if stored.days.count != before { scheduleSave() }
    }

    private func scheduleSave() {
        guard saveTimer == nil else { return }
        let timer = Timer(timeInterval: 5, target: self, selector: #selector(saveTimerFired), userInfo: nil, repeats: false)
        timer.tolerance = 2
        RunLoop.main.add(timer, forMode: .common)
        saveTimer = timer
    }

    @objc private func saveTimerFired() {
        saveNow()
    }

    /// Writes any pending change; called on quit.
    func saveNow() {
        guard saveTimer != nil else { return }
        saveTimer?.invalidate()
        saveTimer = nil

        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        do {
            // The fallback words are things you typed: owner-only access.
            try ClipImageFile.createPrivateDirectory(fileURL.deletingLastPathComponent())
            try encoder.encode(stored).write(to: fileURL, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
        } catch {
            NSLog("Launcher: could not save usage stats: \(error)")
        }
    }

    private func load() {
        do {
            let data = try Data(contentsOf: fileURL)
            stored = try JSONDecoder().decode(StoredUsage.self, from: data)
        } catch CocoaError.fileReadNoSuchFile {
            // First launch: nothing recorded yet.
        } catch {
            // Unreadable or undecodable: set it aside rather than overwrite it
            // on the next save, in case it can be recovered by hand.
            let backup = fileURL.deletingPathExtension().appendingPathExtension("unreadable.json")
            try? FileManager.default.removeItem(at: backup)
            try? FileManager.default.moveItem(at: fileURL, to: backup)
            NSLog("Launcher: unreadable usage stats moved to \(backup.path): \(error)")
        }
    }
}
